@implementation NGLevelData

static NSArray<NGPuzzle *> *_cachedLevels = nil;

+ (NSArray<NGPuzzle *> *)allLevels {
    if (_cachedLevels) return _cachedLevels;
    _cachedLevels = [self buildAllLevels];
    return _cachedLevels;
}

+ (nullable NGPuzzle *)puzzleForLevel:(NSInteger)level {
    NSArray *all = [self allLevels];
    if (level < 1 || level > (NSInteger)all.count) return nil;
    return all[level - 1];
}

+ (NSInteger)totalLevelCount { return 99; }

+ (NSArray<NGPuzzle *> *)buildAllLevels {
    NSMutableArray *levels = [NSMutableArray arrayWithCapacity:99];
    [levels addObjectsFromArray:[self levels_1_to_15]];
    [levels addObjectsFromArray:[self levels_16_to_30]];
    [levels addObjectsFromArray:[self levels_31_to_45]];
    [levels addObjectsFromArray:[self levels_46_to_60]];
    [levels addObjectsFromArray:[self levels_61_to_72]];
    [levels addObjectsFromArray:[self levels_73_to_85]];
    [levels addObjectsFromArray:[self levels_86_to_99]];
    return [levels copy];
}

