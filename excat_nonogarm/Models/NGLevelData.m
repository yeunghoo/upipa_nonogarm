/// Build a 1-5 color NSArray from NGTheme palette indices.
static NSArray *C1(NSInteger a) {
    return @[[NGTheme puzzleColorForIndex:a]];
}
static NSArray *C2(NSInteger a, NSInteger b) {
    return @[[NGTheme puzzleColorForIndex:a], [NGTheme puzzleColorForIndex:b]];
}
static NSArray *C3(NSInteger a, NSInteger b, NSInteger c) {
    return @[[NGTheme puzzleColorForIndex:a],
             [NGTheme puzzleColorForIndex:b],
             [NGTheme puzzleColorForIndex:c]];
}
static NSArray *C4(NSInteger a, NSInteger b, NSInteger c, NSInteger d) {
    return @[[NGTheme puzzleColorForIndex:a],
             [NGTheme puzzleColorForIndex:b],
             [NGTheme puzzleColorForIndex:c],
             [NGTheme puzzleColorForIndex:d]];
}
static NSArray *C5(NSInteger a, NSInteger b, NSInteger c, NSInteger d, NSInteger e) {
    return @[[NGTheme puzzleColorForIndex:a],
             [NGTheme puzzleColorForIndex:b],
             [NGTheme puzzleColorForIndex:c],
             [NGTheme puzzleColorForIndex:d],
             [NGTheme puzzleColorForIndex:e]];
}

/// Append one puzzle to the mutable array — no macros, plain C function.
static void addP(NSMutableArray *arr,
                 NSString       *grid,
                 NSArray        *colors,
                 NSString       *name,
                 NSInteger       level) {
    [arr addObject:[NGPuzzle puzzleWithGridString:grid
                                          colors:colors
                                            name:name
                                           level:level]];
}

